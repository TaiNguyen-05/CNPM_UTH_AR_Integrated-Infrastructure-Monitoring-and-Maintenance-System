from marshmallow import Schema, fields, validate


class NodeSchema(Schema):
    id = fields.Str(dump_only=False, required=False)
    rack_id = fields.Str(required=True)
    name = fields.Str(required=True, validate=validate.Length(min=2))
    u_start = fields.Int(required=True, validate=validate.Range(min=1, max=48))
    u_height = fields.Int(load_default=2, validate=validate.Range(min=1, max=10))
    slot = fields.Str(dump_only=True)
    ip_address = fields.Str(required=True)
    mac_address = fields.Str(allow_none=True)
    model = fields.Str(allow_none=True)
    cpu_model = fields.Str(allow_none=True)
    ram_total_gb = fields.Int(load_default=32, validate=validate.Range(min=1))
    disk_total_gb = fields.Int(load_default=1000, validate=validate.Range(min=1))
    qr_code_payload = fields.Str(allow_none=True)
    status = fields.Str(load_default="HEALTHY", validate=validate.OneOf(["HEALTHY", "WARNING", "CRITICAL", "OFFLINE"]))
    metrics = fields.Dict(allow_none=True)
    containers = fields.List(fields.Dict(), allow_none=True)
    last_heartbeat_at = fields.Str(dump_only=True)
    created_at = fields.Str(dump_only=True)
    updated_at = fields.Str(dump_only=True)


class RackSchema(Schema):
    id = fields.Str(dump_only=False, required=False)
    name = fields.Str(required=True, validate=validate.Length(min=2))
    code = fields.Str(required=True)
    room_name = fields.Str(load_default="Server Room 01")
    total_u = fields.Int(load_default=42, validate=validate.Range(min=12, max=60))
    power_limit_kw = fields.Float(load_default=10.0, validate=validate.Range(min=0.1))
    x_coord = fields.Float(load_default=0.0)
    y_coord = fields.Float(load_default=0.0)
    created_at = fields.Str(dump_only=True)
    updated_at = fields.Str(dump_only=True)


class AlertSchema(Schema):
    id = fields.Str(dump_only=False, required=False)
    server_node_id = fields.Str(required=True)
    severity = fields.Str(load_default="WARNING", validate=validate.OneOf(["INFO", "WARNING", "CRITICAL"]))
    title = fields.Str(required=True, validate=validate.Length(min=2))
    message = fields.Str(required=True)
    metric_name = fields.Str(load_default="cpu")
    metric_value = fields.Float(load_default=0.0)
    threshold_value = fields.Float(load_default=80.0)
    status = fields.Str(load_default="OPEN", validate=validate.OneOf(["OPEN", "ACKNOWLEDGED", "RESOLVED", "DISMISSED"]))
    acknowledged_by = fields.Str(allow_none=True)
    acknowledged_at = fields.Str(dump_only=True)
    resolved_by = fields.Str(allow_none=True)
    resolved_at = fields.Str(dump_only=True)
    created_at = fields.Str(dump_only=True)
    updated_at = fields.Str(dump_only=True)


class TicketSchema(Schema):
    id = fields.Str(dump_only=False, required=False)
    server_node_id = fields.Str(required=True)
    alert_id = fields.Str(allow_none=True)
    title = fields.Str(required=True, validate=validate.Length(min=3))
    description = fields.Str(allow_none=True)
    priority = fields.Str(load_default="MEDIUM", validate=validate.OneOf(["LOW", "MEDIUM", "HIGH", "CRITICAL"]))
    status = fields.Str(load_default="CREATED", validate=validate.OneOf(["CREATED", "ASSIGNED", "IN_PROGRESS", "PENDING_PARTS", "RESOLVED", "CLOSED"]))
    assigned_technician_id = fields.Str(allow_none=True)
    assigned_technician_name = fields.Str(allow_none=True)
    created_by = fields.Str(allow_none=True)
    resolution_notes = fields.Str(allow_none=True)
    ar_session_logs = fields.List(fields.Dict(), dump_only=True)
    started_at = fields.Str(dump_only=True)
    resolved_at = fields.Str(dump_only=True)
    closed_at = fields.Str(dump_only=True)
    created_at = fields.Str(dump_only=True)
    updated_at = fields.Str(dump_only=True)


class UserSchema(Schema):
    id = fields.Str(dump_only=False, required=False)
    email = fields.Email(required=True)
    full_name = fields.Str(required=True, validate=validate.Length(min=2))
    role = fields.Str(load_default="TECHNICIAN", validate=validate.OneOf(["ADMIN", "OPERATOR", "TECHNICIAN"]))
    status = fields.Str(load_default="PENDING_APPROVAL", validate=validate.OneOf(["PENDING_APPROVAL", "APPROVED", "LOCKED", "REJECTED"]))
    phone_number = fields.Str(allow_none=True)
    department = fields.Str(load_default="Infrastructure Ops")
    avatar = fields.Str(allow_none=True)
    approved_by = fields.Str(allow_none=True)
    approved_at = fields.Str(dump_only=True)
    created_at = fields.Str(dump_only=True)
    updated_at = fields.Str(dump_only=True)
